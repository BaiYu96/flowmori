public enum ClipboardPolicy {
    public static let ignoredTypes: Set<String> = [
        "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType", "org.nspasteboard.RestoredType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping", "Pasteboard generator type", "app.flowmori.own-copy", ProductMigration.legacyOwnCopyType
    ]
    public static func shouldIgnore(types: Set<String>, source: String, exclusions: Set<String>) -> Bool {
        !ignoredTypes.isDisjoint(with: types) || types.contains("public.file-url") || exclusions.contains(source)
    }
}

public enum ScreenGeometry {
    /// AppKit uses a bottom-left origin; display image pixels use a top-left origin.
    public static func pixelCrop(selection: CGRect, screen: CGRect, pixelWidth: Int, pixelHeight: Int) -> CGRect {
        let region = selection.standardized.intersection(screen)
        guard !region.isNull, screen.width > 0, screen.height > 0 else { return .zero }
        let sx = CGFloat(pixelWidth) / screen.width, sy = CGFloat(pixelHeight) / screen.height
        let x0 = floor((region.minX - screen.minX) * sx)
        let y0 = floor((screen.maxY - region.maxY) * sy)
        let x1 = ceil((region.maxX - screen.minX) * sx)
        let y1 = ceil((screen.maxY - region.minY) * sy)
        return CGRect(x: x0, y: y0, width: x1 - x0, height: y1 - y0)
            .intersection(CGRect(x: 0, y: 0, width: pixelWidth, height: pixelHeight))
    }
    public static func clamped(_ frame: CGRect, to available: CGRect) -> CGRect {
        let width = min(frame.width, available.width), height = min(frame.height, available.height)
        return CGRect(x: min(max(frame.minX, available.minX), available.maxX - width),
                      y: min(max(frame.minY, available.minY), available.maxY - height), width: width, height: height)
    }
    /// Resize a pinned image without imposing a minimum on both dimensions;
    /// a very wide screenshot must remain zoomable without changing its ratio.
    public static func scaledImageFrame(_ frame:CGRect, factor:CGFloat, available:CGRect) -> CGRect {
        guard frame.width > 0, frame.height > 0, factor.isFinite, factor > 0,
              available.width > 0, available.height > 0 else { return frame }
        let maximum = min(available.width/frame.width,available.height/frame.height)
        let minimum = min(maximum,60/max(frame.width,frame.height))
        let scale = min(maximum,max(minimum,factor))
        let size = CGSize(width:frame.width*scale,height:frame.height*scale)
        return clamped(CGRect(x:frame.midX-size.width/2,y:frame.midY-size.height/2,width:size.width,height:size.height),to:available)
    }
}

public struct MenuOperationState: Equatable {
    public enum Phase: Equatable { case idle, moving, interacting, restoring, failed }
    public private(set) var phase: Phase = .idle
    public private(set) var windowID: UInt32?
    public init() {}
    public mutating func begin(_ id: UInt32) -> Bool {
        guard phase == .idle else { return false }
        windowID = id; phase = .moving; return true
    }
    public mutating func didMove() { if phase == .moving { phase = .interacting } }
    public mutating func restore() { if windowID != nil { phase = .restoring } }
    public mutating func finish() { windowID = nil; phase = .idle }
    public mutating func fail() { phase = .failed }
}
