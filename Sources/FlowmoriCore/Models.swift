public enum ClipKind: String, Codable, Sendable { case text, image }

public struct ClipPayload: Sendable {
    public var kind: ClipKind
    public var text: String
    public var representations: [String: Data]
    public var imagePNG: Data?
    public var sourceBundleID: String
    public var sourceName: String

    public init(kind: ClipKind, text: String = "", representations: [String: Data] = [:],
                imagePNG: Data? = nil, sourceBundleID: String = "", sourceName: String = "") {
        self.kind = kind; self.text = text; self.representations = representations
        self.imagePNG = imagePNG; self.sourceBundleID = sourceBundleID; self.sourceName = sourceName
    }

    public var fingerprint: String {
        var hash = SHA256()
        hash.update(data: Data(kind.rawValue.utf8))
        if let imagePNG { hash.update(data: imagePNG) }
        else { hash.update(data: Data(text.utf8)) }
        return hash.finalize().map { String(format: "%02x", $0) }.joined()
    }
}

